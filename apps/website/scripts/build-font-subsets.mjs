import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(app, 'public/fonts/subsets');
const jsonPath = resolve(output, 'font-subsets-manifest.json');
const tsPath = resolve(app, 'src/generated/font-subsets-manifest.ts');
const sourceFonts = { oppo: resolve(app, 'public/fonts/OPPO Sans 4.0.ttf'), zhuque: resolve(app, 'public/fonts/ZhuqueFangsong-Regular.ttf') };
const python = process.env.FONTTOOLS_PYTHON || (existsSync(resolve(app, '../../.venv/bin/python')) ? resolve(app, '../../.venv/bin/python') : 'python3');
const sha = data => createHash('sha256').update(data).digest('hex');
const files = dir => readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
  const path = resolve(dir, entry.name);
  return entry.isDirectory() ? files(path) : /\.(ts|tsx|astro)$/.test(entry.name) ? [path] : [];
});
const sources = files(resolve(app, 'src')).filter(path => !path.includes('/generated/'));
const ascii = Array.from({ length: 95 }, (_, index) => String.fromCharCode(index + 32)).join('');
// Shared UI labels can occur outside i18n modules. Include their Unicode glyphs too.
const shared = sources.filter(path => /\.(tsx|astro)$/.test(path)).map(path => readFileSync(path, 'utf8').replace(/[\x00-\x7f]/g, '')).join('');
const localeSources = Object.fromEntries(['en', 'zh'].map(locale => [locale, sources.filter(path => basename(path) === `${locale}.ts`)]));
const characters = Object.fromEntries(Object.entries(localeSources).map(([locale, paths]) => [locale,
  [...new Set(Array.from(ascii + shared + paths.map(path => readFileSync(path, 'utf8')).join('')))]
    .sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).join('')
]));
const fingerprint = sha(JSON.stringify({ recipe: 'weight-400-woff2-v2', characters,
  fonts: Object.fromEntries(Object.entries(sourceFonts).map(([key, path]) => [key, sha(readFileSync(path))])),
  tools: readFileSync(resolve(app, 'scripts/requirements-fonts.txt'), 'utf8') }));
const manifestSource = manifest => `// This file is auto-generated by scripts/build-font-subsets.mjs\nexport const fontSubsetsManifest = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type FontSubsetLocale = keyof typeof fontSubsetsManifest;\n`;
function currentBuild() {
  try {
    const { _build, ...manifest } = JSON.parse(readFileSync(jsonPath, 'utf8'));
    const validFiles = Object.values(manifest).every(entry => Object.values(entry).every(name => {
      const path = resolve(output, name);
      return existsSync(path) && name.includes(sha(readFileSync(path)).slice(0, 8));
    }));
    return _build === fingerprint && validFiles && readFileSync(tsPath, 'utf8') === manifestSource(manifest);
  } catch { return false; }
}
if (currentBuild()) {
  console.log('Font subsets match current sources.');
} else {
  if (process.argv.includes('--check')) throw new Error('Font subsets are stale. Run pnpm build:fonts with the pinned Python requirements installed.');
  const probe = spawnSync(python, ['-c', 'import fontTools, brotli'], { encoding: 'utf8' });
  if (probe.status !== 0) throw new Error('Font tools are required for changed text. Install scripts/requirements-fonts.txt in .venv; optionally set FONTTOOLS_PYTHON.');
  const staging = mkdtempSync(resolve(tmpdir(), 'website-fonts-'));
  const run = args => {
    const result = spawnSync(python, args, { encoding: 'utf8', env: { ...process.env, SOURCE_DATE_EPOCH: '0' } });
    if (result.status !== 0) throw new Error(`Font generation failed:\n${result.stderr || result.error}`);
  };
  try {
    const staticOppo = resolve(staging, 'oppo-400.ttf');
    run(['-m', 'fontTools.varLib.instancer', sourceFonts.oppo, 'wght=400', '--static', '--output', staticOppo]);
    const manifest = {};
    for (const [locale, text] of Object.entries(characters)) {
      const textPath = resolve(staging, `${locale}.txt`);
      writeFileSync(textPath, text);
      const entry = {};
      for (const [key, family, source] of [['oppoSans400', 'oppo-sans-400', staticOppo], ['zhuqueFangsong400', 'zhuque-fangsong-400', sourceFonts.zhuque]]) {
        const temporary = resolve(staging, `${family}-${locale}.woff2`);
        run(['-m', 'fontTools.subset', source, '--flavor=woff2', `--output-file=${temporary}`, `--text-file=${textPath}`, '--layout-features=*', '--no-hinting', '--no-recalc-timestamp']);
        entry[key] = `${family}-${locale}.${sha(readFileSync(temporary)).slice(0, 8)}.woff2`;
        renameSync(temporary, resolve(staging, entry[key]));
      }
      manifest[locale] = entry;
    }
    // Publish only after every subset succeeded. Old fonts survive a failed build.
    mkdirSync(output, { recursive: true });
    for (const entry of Object.values(manifest)) for (const name of Object.values(entry)) renameSync(resolve(staging, name), resolve(output, name));
    writeFileSync(resolve(staging, 'manifest.json'), `${JSON.stringify({ _build: fingerprint, ...manifest }, null, 2)}\n`);
    writeFileSync(resolve(staging, 'manifest.ts'), manifestSource(manifest));
    renameSync(resolve(staging, 'manifest.ts'), tsPath);
    renameSync(resolve(staging, 'manifest.json'), jsonPath);
    const used = new Set(Object.values(manifest).flatMap(Object.values));
    for (const name of readdirSync(output)) if (/^(oppo-sans-400|zhuque-fangsong-400)-.*\.woff2$/.test(name) && !used.has(name)) rmSync(resolve(output, name));
    console.log('Generated verified en/zh font subsets.');
  } finally { rmSync(staging, { recursive: true, force: true }); }
}
